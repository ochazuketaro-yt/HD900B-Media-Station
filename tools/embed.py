#!/usr/bin/env python3
"""embed.py: turn www/index.html into src/ui_html.h (a C++ raw string literal, split to stay below compiler string limits)."""
import sys
src, dst = sys.argv[1], sys.argv[2]
data = open(src, encoding="utf-8").read()
assert ")MSUI\"" not in data
chunks = [data[i:i + 8000] for i in range(0, len(data), 8000)]
out = ["// generated by tools/embed.py -- do not edit", "#pragma once", "static const char UI_HTML[] ="]
for c in chunks:
    out.append('R"MSUI(' + c + ')MSUI"')
out.append(";")
open(dst, "w", encoding="utf-8").write("\n".join(out) + "\n")
print("embedded", len(data), "bytes")
